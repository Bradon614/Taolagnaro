#!/usr/bin/env python3
"""Turns the download manifest into the typed module the app reads."""
import json

m = json.load(open("scripts/photos-manifest.json"))

def esc(s):
    return (s or "").replace("\\", "\\\\").replace('"', '\\"')

rows = []
for p in sorted(m, key=lambda x: (x["target"], x["role"] != "lead", x["id"])):
    rows.append(f'''  {{
    id: "{p['id']}",
    src: "{p['src']}",
    target: "{p['target']}",
    role: "{p['role']}",
    width: {p['width']},
    height: {p['height']},
    caption: {{ fr: "{esc(p['caption']['fr'])}", en: "{esc(p['caption']['en'])}" }},
    author: "{esc(p['author'])}",
    licence: "{esc(p['licence'])}",
    licenceUrl: "{esc(p['licenceUrl'])}",
    source: "{esc(p['source'])}",
  }},''')

out = '''/**
 * Photograph manifest — generated by scripts/gen-photos-ts.py from the
 * Wikimedia Commons selection. Do not edit by hand; edit
 * scripts/commons-selection.json and re-run the fetch.
 *
 * Every entry carries its author, licence and source because most of these
 * are CC BY-SA: showing the image without the credit is a licence breach, so
 * the obligation travels with the data rather than being remembered
 * separately.
 *
 * Listings with no photograph here keep their generated plate. That is not a
 * placeholder — the bathymetric plate is part of the visual identity, and a
 * mixed page of photographs and plates stays coherent.
 */

import type { Locale } from "@/i18n/config";

export type Photo = {
  id: string;
  src: string;
  /** A listing slug, or "_region" / "_spiny-forest" for editorial use. */
  target: string;
  role: "lead" | "gallery";
  width: number;
  height: number;
  caption: { fr: string; en: string };
  author: string;
  licence: string;
  licenceUrl: string;
  source: string;
};

export const PHOTOS: Photo[] = [
''' + "\n".join(rows) + '''
];

/** Every photograph for a listing, lead first. */
export function photosFor(target: string): Photo[] {
  return PHOTOS.filter((photo) => photo.target === target);
}

/** The single image that represents a listing on a card, if it has one. */
export function leadPhoto(target: string): Photo | undefined {
  const all = photosFor(target);
  return all.find((photo) => photo.role === "lead") ?? all[0];
}

export function photoCaption(photo: Photo, locale: Locale): string {
  return locale === "en" ? photo.caption.en : photo.caption.fr;
}

/** Short credit line, e.g. "Hiroki Ogawa · CC BY-SA 3.0". */
export function photoCredit(photo: Photo): string {
  return `${photo.author} · ${photo.licence}`;
}
'''
open("src/lib/photos.ts", "w").write(out)
print(f"src/lib/photos.ts — {len(m)} entrées")
